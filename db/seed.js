function seedDatabase(db) {
  const insertSetting = db.prepare("INSERT OR IGNORE INTO site_settings (key, value) VALUES (?, ?)");
  for (const [key, value] of Object.entries(DEFAULT_SETTINGS)) insertSetting.run(key, value);

  const count = db.prepare("SELECT COUNT(*) AS n FROM restaurants").get().n;
  if (Number(count) > 0) return;

  const insertRestaurant = db.prepare(
    "INSERT INTO restaurants (name, cuisine, description, address, phone, hours, image, rating) VALUES (?, ?, ?, ?, ?, ?, ?, ?)"
  );
  const insertItem = db.prepare(
    "INSERT INTO menu_items (restaurant_id, category, name, description, price, emoji) VALUES (?, ?, ?, ?, ?, ?)"
  );

  db.exec("BEGIN");
  try {
    for (const r of RESTAURANTS) {
      const result = insertRestaurant.run(r.name, r.cuisine, r.description, r.address, r.phone, r.hours, r.image, r.rating);
      const id = Number(result.lastInsertRowid);
      for (const [category, name, description, price, emoji] of r.menu) {
        insertItem.run(id, category, name, description, price, emoji);
      }
    }
    db.exec("COMMIT");
  } catch (err) {
    db.exec("ROLLBACK");
    throw err;
  }
  console.log("Ավելացվեցին օրինակային ռեստորաններ և մենյուներ");
}

module.exports = { seedDatabase, DEFAULT_SETTINGS };
