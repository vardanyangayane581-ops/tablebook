const SEED_KEY = "seed_regions_v1";

function seedRegions(db) {
  if (db.prepare("SELECT 1 FROM site_settings WHERE key = ?").get(SEED_KEY)) return;

  const insertRestaurant = db.prepare(
    "INSERT INTO restaurants (name, cuisine, description, address, phone, hours, image, rating, region, city) " +
    "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)"
  );
  const insertItem = db.prepare(
    "INSERT INTO menu_items (restaurant_id, category, name, description, price, emoji) VALUES (?, ?, ?, ?, ?, ?)"
  );
  const exists = db.prepare("SELECT 1 FROM restaurants WHERE name = ?");

  db.exec("BEGIN");
  try {
    PLACES.forEach(([name, city, kind, description, image, rating, hours], index) => {
      if (exists.get(name)) return;
      const region = regionOfCity(city);
      const n = String(index + 1).padStart(2, "0");
      const result = insertRestaurant.run(
        name,
        CUISINES[kind],
        description,
        "Օրինակ փողոց " + (index % 40 + 1) + ", " + city,
        "+374 00 " + n + " " + n + " " + n,
        hours,
        image === "region" ? regionImage(region.id) : image,
        rating,
        region.id,
        city
      );
      const id = Number(result.lastInsertRowid);
      for (const [category, item, text, price, emoji] of MENUS[kind]) {
        insertItem.run(id, category, item, text, price, emoji);
      }
    });
    db.prepare("INSERT INTO site_settings (key, value) VALUES (?, ?)").run(SEED_KEY, "1");
    db.exec("COMMIT");
  } catch (err) {
    db.exec("ROLLBACK");
    throw err;
  }
  console.log("Ավելացվեցին մարզերի օրինակային ռեստորաններ");
}

module.exports = { seedRegions };
